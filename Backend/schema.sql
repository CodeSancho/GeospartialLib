-- Fresh development schema for the GeospatialLib API.
-- Run this while connected to the geospatial database as a user allowed to
-- install PostGIS (or have an administrator install the extension first).

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projects (
  project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL,
  location TEXT NOT NULL,
  start_date DATE,
  end_date DATE,
  geom geometry(Geometry, 4326)
);

CREATE TABLE IF NOT EXISTS drillholes (
  drillhole_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
  hole_id TEXT NOT NULL,
  easting DOUBLE PRECISION NOT NULL,
  northing DOUBLE PRECISION NOT NULL,
  elevation DOUBLE PRECISION,
  max_depth DOUBLE PRECISION,
  contractor_id BIGINT,
  coordinate_system TEXT,
  start_date DATE,
  end_date DATE,
  azimuth DOUBLE PRECISION,
  dip DOUBLE PRECISION,
  status TEXT,
  geom geometry(Point, 4326),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (project_id, hole_id)
);

CREATE TABLE IF NOT EXISTS samples (
  sample_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drillhole_id BIGINT NOT NULL REFERENCES drillholes(drillhole_id) ON DELETE CASCADE,
  sample_code TEXT,
  from_depth DOUBLE PRECISION,
  to_depth DOUBLE PRECISION,
  sample_type TEXT,
  date_collected DATE,
  geom geometry(Geometry, 4326)
);

CREATE TABLE IF NOT EXISTS assayresults (
  result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sample_id BIGINT NOT NULL REFERENCES samples(sample_id) ON DELETE CASCADE,
  element TEXT NOT NULL,
  value DOUBLE PRECISION,
  units TEXT,
  detection_limit DOUBLE PRECISION,
  lab_name TEXT,
  analysis_date DATE
);

CREATE TABLE IF NOT EXISTS geologylogs (
  log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sample_id BIGINT NOT NULL REFERENCES samples(sample_id) ON DELETE CASCADE,
  lithology TEXT,
  alteration TEXT,
  structure TEXT,
  notes TEXT
);

CREATE TABLE IF NOT EXISTS geophysicslogs (
  geophys_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drillhole_id BIGINT NOT NULL REFERENCES drillholes(drillhole_id) ON DELETE CASCADE,
  depth DOUBLE PRECISION NOT NULL,
  log_type TEXT NOT NULL,
  log_value DOUBLE PRECISION,
  units TEXT
);

CREATE TABLE IF NOT EXISTS geotechnicalhydro (
  geo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sample_id BIGINT NOT NULL REFERENCES samples(sample_id) ON DELETE CASCADE,
  rqd_percent DOUBLE PRECISION,
  recovery_percent DOUBLE PRECISION,
  groundwater_obs TEXT,
  strength_test TEXT,
  notes TEXT
);

CREATE TABLE IF NOT EXISTS propertytemplates (
  template_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  commodity_type TEXT NOT NULL,
  property_name TEXT NOT NULL,
  units TEXT,
  property_category TEXT,
  is_required BOOLEAN NOT NULL DEFAULT FALSE,
  display_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sampleproperties (
  property_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sample_id BIGINT NOT NULL REFERENCES samples(sample_id) ON DELETE CASCADE,
  property_name TEXT NOT NULL,
  property_value TEXT,
  units TEXT,
  property_category TEXT,
  notes TEXT
);

CREATE INDEX IF NOT EXISTS drillholes_geom_gix ON drillholes USING GIST (geom);
CREATE INDEX IF NOT EXISTS projects_geom_gix ON projects USING GIST (geom);
CREATE INDEX IF NOT EXISTS samples_geom_gix ON samples USING GIST (geom);
CREATE INDEX IF NOT EXISTS drillholes_project_id_idx ON drillholes (project_id);
CREATE INDEX IF NOT EXISTS samples_drillhole_id_idx ON samples (drillhole_id);

-- These views support the reports routes if reports are enabled in app.js.
CREATE OR REPLACE VIEW vw_project_summary AS
SELECT p.project_id, p.name, p.location,
       COUNT(DISTINCT d.drillhole_id) AS drillhole_count,
       COUNT(DISTINCT s.sample_id) AS sample_count
FROM projects p
LEFT JOIN drillholes d ON d.project_id = p.project_id
LEFT JOIN samples s ON s.drillhole_id = d.drillhole_id
GROUP BY p.project_id, p.name, p.location;

CREATE OR REPLACE VIEW vw_project_drillholes AS
SELECT p.name AS project_name, d.*
FROM projects p JOIN drillholes d ON d.project_id = p.project_id;

CREATE OR REPLACE VIEW vw_samples_in_project AS
SELECT p.project_id, p.name AS project_name, d.hole_id, s.*
FROM projects p
JOIN drillholes d ON d.project_id = p.project_id
JOIN samples s ON s.drillhole_id = d.drillhole_id;

CREATE OR REPLACE VIEW vw_avg_grade AS
SELECT d.project_id, d.drillhole_id, d.hole_id, ar.element,
       AVG(ar.value) AS average_grade, ar.units
FROM drillholes d
JOIN samples s ON s.drillhole_id = d.drillhole_id
JOIN assayresults ar ON ar.sample_id = s.sample_id
GROUP BY d.project_id, d.drillhole_id, d.hole_id, ar.element, ar.units;
